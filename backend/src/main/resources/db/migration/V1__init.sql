-- ---------------------------------------------------------------------
-- USUARIO
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    email           VARCHAR(150) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    rol             VARCHAR(20)  NOT NULL,
    creado_en       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_rol   CHECK (rol IN ('CLIENTE', 'RESTAURANTE', 'ADMIN'))
);

-- ---------------------------------------------------------------------
-- RESTAURANTE
-- ---------------------------------------------------------------------
CREATE TABLE restaurante (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        BIGINT           NOT NULL,
    nombre            VARCHAR(120)     NOT NULL,
    direccion         VARCHAR(255)     NOT NULL,
    latitud           DOUBLE PRECISION NOT NULL,
    longitud          DOUBLE PRECISION NOT NULL,
    categoria         VARCHAR(50)      NOT NULL,
    estado            VARCHAR(20)      NOT NULL DEFAULT 'PENDIENTE',
    puntaje_promedio  NUMERIC(3,2)     NOT NULL DEFAULT 0,
    total_resenas     INTEGER          NOT NULL DEFAULT 0,
    creado_en         TIMESTAMPTZ      NOT NULL DEFAULT now(),
    actualizado_en    TIMESTAMPTZ      NOT NULL DEFAULT now(),

    CONSTRAINT fk_restaurante_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT uk_restaurante_usuario UNIQUE (usuario_id),   -- un restaurante por usuario
    CONSTRAINT ck_restaurante_estado  CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO')),
    CONSTRAINT ck_restaurante_latitud CHECK (latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_restaurante_longitud CHECK (longitud BETWEEN -180 AND 180)
);

CREATE INDEX idx_restaurante_estado ON restaurante (estado);

-- ---------------------------------------------------------------------
-- PACK
-- ---------------------------------------------------------------------
CREATE TABLE pack (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id   BIGINT        NOT NULL,
    titulo           VARCHAR(120)  NOT NULL,
    descripcion      VARCHAR(500),
    precio_original  NUMERIC(10,2) NOT NULL,
    precio_oferta    NUMERIC(10,2) NOT NULL,
    stock            INTEGER       NOT NULL,
    recojo_desde     TIMESTAMPTZ   NOT NULL,
    recojo_hasta     TIMESTAMPTZ   NOT NULL,
    estado           VARCHAR(20)   NOT NULL DEFAULT 'ACTIVO',
    creado_en        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_pack_restaurante FOREIGN KEY (restaurante_id) REFERENCES restaurante (id),
    CONSTRAINT ck_pack_stock       CHECK (stock >= 0),       -- nunca stock negativo
    CONSTRAINT ck_pack_precios     CHECK (precio_oferta > 0 AND precio_oferta < precio_original),
    CONSTRAINT ck_pack_recojo      CHECK (recojo_hasta > recojo_desde),
    CONSTRAINT ck_pack_estado      CHECK (estado IN ('ACTIVO', 'AGOTADO', 'EXPIRADO'))
);

CREATE INDEX idx_pack_restaurante     ON pack (restaurante_id);
CREATE INDEX idx_pack_estado_recojo   ON pack (estado, recojo_hasta);   -- listado y job de expiración

-- ---------------------------------------------------------------------
-- RESERVA
-- ---------------------------------------------------------------------
CREATE TABLE reserva (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id           BIGINT        NOT NULL,
    pack_id              BIGINT        NOT NULL,
    cantidad             INTEGER       NOT NULL,
    total                NUMERIC(10,2) NOT NULL,
    codigo_recojo        VARCHAR(12)   NOT NULL,
    estado               VARCHAR(20)   NOT NULL DEFAULT 'PENDIENTE_PAGO',
    expira_en            TIMESTAMPTZ   NOT NULL,
    reembolso_pendiente  BOOLEAN       NOT NULL DEFAULT FALSE,
    creado_en            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en       TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_reserva_cliente FOREIGN KEY (cliente_id) REFERENCES usuario (id),
    CONSTRAINT fk_reserva_pack    FOREIGN KEY (pack_id)    REFERENCES pack (id),
    CONSTRAINT uk_reserva_codigo  UNIQUE (codigo_recojo),
    CONSTRAINT ck_reserva_cantidad CHECK (cantidad BETWEEN 1 AND 2),
    CONSTRAINT ck_reserva_total    CHECK (total > 0),
    CONSTRAINT ck_reserva_estado   CHECK (estado IN ('PENDIENTE_PAGO', 'PAGADA', 'RECOGIDA', 'CANCELADA', 'EXPIRADA'))
);

CREATE INDEX idx_reserva_cliente        ON reserva (cliente_id);
CREATE INDEX idx_reserva_pack           ON reserva (pack_id);
CREATE INDEX idx_reserva_estado_expira  ON reserva (estado, expira_en);  -- job de expiración

-- ---------------------------------------------------------------------
-- PAGO
-- ---------------------------------------------------------------------
CREATE TABLE pago (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id  BIGINT        NOT NULL,
    proveedor   VARCHAR(30)   NOT NULL,
    referencia  VARCHAR(100)  NOT NULL,
    monto       NUMERIC(10,2) NOT NULL,
    estado      VARCHAR(20)   NOT NULL,
    creado_en   TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_pago_reserva FOREIGN KEY (reserva_id) REFERENCES reserva (id),
    CONSTRAINT ck_pago_monto   CHECK (monto > 0),
    CONSTRAINT ck_pago_estado  CHECK (estado IN ('APROBADO', 'RECHAZADO', 'REEMBOLSADO'))
);

-- Idempotencia: una reserva solo puede tener UN pago aprobado
CREATE UNIQUE INDEX uk_pago_reserva_aprobado ON pago (reserva_id) WHERE estado = 'APROBADO';

-- ---------------------------------------------------------------------
-- RESENA
-- ---------------------------------------------------------------------
CREATE TABLE resena (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id  BIGINT       NOT NULL,
    puntaje     SMALLINT     NOT NULL,
    comentario  VARCHAR(500),
    creado_en   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_resena_reserva FOREIGN KEY (reserva_id) REFERENCES reserva (id),
    CONSTRAINT uk_resena_reserva UNIQUE (reserva_id),          -- una reseña por reserva
    CONSTRAINT ck_resena_puntaje CHECK (puntaje BETWEEN 1 AND 5)
);
